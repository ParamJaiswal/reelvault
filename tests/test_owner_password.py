"""`scripts/set_owner_password.py` — the only way to satisfy the stale-owner-
credentials warning without hand-editing the database.

This writes the one credential that guards every other one, so the tests are
about the failure paths: a refused password must leave both the old hash and the
credentials file exactly as they were, because the file is the only copy of what
currently works. The hash/verify roundtrip itself is `test_prod.py`'s; the
read-back here checks that the write reached the row the login path reads.
"""
from pathlib import Path

import pytest

from app.core.auth import ensure_owner_user, verify_password
from app.core.config import settings
from app.db.schema import get_db
from scripts.set_owner_password import MIN_PASSWORD_CHARS, set_owner_password

CRED_FILE = ".owner_credentials.txt"
NEW_PASSWORD = "a-long-enough-new-password"


def _owner():
    with get_db() as db:
        return dict(db.execute("SELECT password_hash, password_salt FROM users"
                               " WHERE role='owner'").fetchone())


@pytest.fixture()
def owner_with_credentials_file(tmp_db):
    """The state the script exists for: an owner whose password exists only in
    the plaintext file next to the database. `ensure_owner_user` returns the
    owner row, not the generated password, so the file body is a sentinel — the
    assertions below are about whether the file is still there."""
    owner = ensure_owner_user()
    cred = Path(settings.data_dir) / CRED_FILE
    cred.write_text("ReelVault owner login\npassword: <auto-generated>\n",
                    encoding="utf-8")
    return owner


def test_the_new_password_replaces_the_old_one_and_the_file_goes(owner_with_credentials_file):
    auto = owner_with_credentials_file["password_hash"]

    result = set_owner_password(NEW_PASSWORD)

    after = _owner()
    assert verify_password(NEW_PASSWORD, after["password_hash"],
                           after["password_salt"])
    assert not verify_password("wrong-" + NEW_PASSWORD, after["password_hash"],
                               after["password_salt"])
    assert after["password_hash"] != auto
    assert result["file_removed"] is True
    assert not Path(settings.data_dir, CRED_FILE).exists()


def test_a_refused_password_changes_neither_hash_nor_file(owner_with_credentials_file):
    before = _owner()

    with pytest.raises(ValueError):
        set_owner_password("x" * (MIN_PASSWORD_CHARS - 1))

    assert _owner() == before
    assert Path(settings.data_dir, CRED_FILE).exists()


def test_no_owner_means_no_hash_is_written_and_the_file_stays(owner_with_credentials_file):
    """A database with no owner is what pointing the script at the wrong file
    looks like. Nothing is changed then, so the file — the only record of the
    password that still works — must survive, and no owner may be created."""
    with get_db() as db:
        db.execute("UPDATE users SET role='viewer' WHERE role='owner'")

    with pytest.raises(LookupError):
        set_owner_password(NEW_PASSWORD)

    assert Path(settings.data_dir, CRED_FILE).exists()
